# markdown -> html
# --------------------------------------------------------------------------
INLINE_CODE = re.compile(r"`([^`]+)`")
BOLD = re.compile(r"\*\*([^*]+)\*\*")
ITALIC = re.compile(r"(?<![*\w])\*([^*\n]+)\*(?!\*)")
LINK = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def escape(text):
    return html.escape(text, quote=False)


def inline(text):
    """Escape, then apply inline markdown. Code spans are extracted first so
    their contents are never treated as markup."""
    spans = []

    def stash(match):
        spans.append(f"<code>{escape(match.group(1))}</code>")
        return f"\x00{len(spans) - 1}\x00"

    text = INLINE_CODE.sub(stash, text)
    text = escape(text)

    def link_sub(match):
        label, href = match.group(1), match.group(2)
        attrs = ""
        if href.startswith("http"):
            attrs = ' target="_blank" rel="noopener"'
        return f'<a href="{html.escape(href, quote=True)}"{attrs}>{label}</a>'

    text = LINK.sub(link_sub, text)
    text = BOLD.sub(r"<strong>\1</strong>", text)
    text = ITALIC.sub(r"<em>\1</em>", text)

    for i, span in enumerate(spans):
        text = text.replace(f"\x00{i}\x00", span)
    return text


def _lang_of(rel_path):
    """Map a repo-relative content path such as content/ko/sources/x.md to
    (lang, path-within-lang). Returns (None, rel_path) if not under content/."""
    parts = rel_path.split("/")
    if len(parts) >= 2 and parts[0] == "content" and parts[1] in ("en", "ko"):
        return parts[1], "/".join(parts[2:])
    return None, rel_path


def _candidates(md_rel_path, href, lang):
    """Yield plausible repo-relative interpretations of href, best first.

    Content files use several relative-link conventions inconsistently:
    relative to their own file (../../ko/...), relative to the language root
    (sources/...), or relative to the repo root (content/ko/...). normpath
    against the file's directory mangles the latter two into nonexistent
    paths, so try each convention and let the filesystem decide.
    """
    src_dir = os.path.dirname(md_rel_path)
    lang_dir = os.path.dirname(f"content/{lang}/x")  # content/<lang>
    seen = set()
    for base in (src_dir, lang_dir, "content", "."):
        cand = os.path.normpath(os.path.join(base, href)).replace(os.sep, "/")
        if cand not in seen:
            seen.add(cand)
            yield cand


def rewrite_md_links(body, md_rel_path, lang):
    """Convert .md links to .html under /<lang>/ served paths.

    Cross-language links appear in several forms: markdown links to
    ../ko/<path>.md, bare language switches like /ko/concepts/x or
    /wiki/ko/x, and content/ko/<path>.md. All must resolve to the sibling
    language's page under the served site root, i.e. /<other>/..., so
    the link works both on disk and in the browser. Same-language absolute
    links (/en/...) are normalised to /en/... too.
    """
    other = "ko" if lang == "en" else "en"
    prefix = f"../{other}/"

    def sub(match):
        label, href = match.group(1), match.group(2)
        if href.startswith(("http", "#", "mailto:")):
            return match.group(0)
        # An unresolved templating token is a content gap, not a real target.
        # Emit the label as plain text rather than a link that 404s.
        if "PLACEHOLDER" in href or href.startswith("[") or href.startswith("{{"):
            return label
        if href.startswith(prefix):
            rest = href[len(prefix) :][: -len(".md")]
            return f"[{label}](/{other}/{rest}.html)"
        # /ko/... or legacy /wiki/ko/... -> sibling language root
        for lead in (f"/{other}/", f"/wiki/{other}/"):
            if href.startswith(lead):
                rest = href[len(lead) :]
                if rest.endswith(".md"):
                    rest = rest[: -len(".md")]
                return f"[{label}](/{other}/{rest}.html)"
        # /en/... or legacy /wiki/en/... -> this language's root
        for lead in (f"/{lang}/", f"/wiki/{lang}/"):
            if href.startswith(lead):
                rest = href[len(lead) :]
                if rest.endswith(".md"):
                    rest = rest[: -len(".md")]
                return f"[{label}](/{lang}/{rest}.html)"
        if not href.endswith(".md"):
            return match.group(0)
        for cand in _candidates(md_rel_path, href, lang):
            cand_lang, cand_rest = _lang_of(cand)
            if cand_lang is None:
                continue
            # test the SOURCE file, not the emitted html, so link resolution
            # does not depend on build ordering
            if not os.path.exists(os.path.join("content", cand_lang, cand_rest)):
                continue
            return f"[{label}](/{cand_lang}/{cand_rest[: -len('.md')]}.html)"
        # unresolved by convention: fall back to a unique basename match in
        # the content tree (handles links with a miscounted number of ../)
        for l in (lang, other):
            hits = glob.glob(
                os.path.join("content", l, "**", os.path.basename(href)), recursive=True
            )
            if len(hits) == 1:
                cand_lang, cand_rest = _lang_of(hits[0].replace(os.sep, "/"))
                if cand_lang:
                    return f"[{label}](/{cand_lang}/{cand_rest[: -len('.md')]}.html)"
        # genuinely unresolvable: leave the original markup untouched
        return match.group(0)

    return LINK.sub(sub, body)


# A line that is nothing but a cross-language "other version" pointer, e.g.
# `[English version](../../../../en/....md)` or `> 한국어: [한국어 버전](/ko/...)`.
# The header switch now covers language switching (and points at the live
# counterpart instead of a possibly renamed target), so these redundant lines
# are dropped. Only standalone lines match: an inline reference inside real
# prose is left alone.
_VERSION_LABEL = re.compile(
    r"^(?:english(?:\s+versions?)?|korean(?:\s+versions?)?|한국어(?:\s*버전)?)\s*$",
    re.IGNORECASE,
)
_VERSION_PREFIX = re.compile(
    r"^(?:english|korean|한국어)(?:\s+versions?)?\s*:\s*$", re.IGNORECASE
)
_VERSION_LINK = re.compile(r"^(.*?)\[([^\]]*)\]\(([^)]*)\)\s*$")
_VERSION_WORD = re.compile(r"versions?|버전", re.IGNORECASE)


def _is_version_link_line(line, lang):
    other = "ko" if lang == "en" else "en"
    s = line.strip()
    if s.startswith(">"):
        s = s[1:].strip()
    m = _VERSION_LINK.match(s)
    if not m:
        return False
    prefix = m.group(1).strip()
    # A leading flag emoji or similar marker is decoration, not content.
    label = re.sub(r"^[^\w\s]+", "", m.group(2)).strip()
    href = m.group(3).strip()
    if _VERSION_LABEL.match(label):
        if not prefix:
            # A bare "[English](...)"-style line is only a version pointer
            # when it says "version" outright or targets the other language.
            return bool(_VERSION_WORD.search(label)
                        or f"/{other}/" in href or f"/{other}/" in label)
        return bool(_VERSION_PREFIX.match(prefix))
    # Link text is something else (e.g. a bare URL as the label) but the
    # line is introduced as a version pointer to the other language.
    if _VERSION_PREFIX.match(prefix):
        target = href + " " + label
        return f"/{other}/" in target or f"/wiki/{other}/" in target
    return False


def strip_version_links(body, lang):
    """Drop standalone other-language version-pointer lines from a body."""
    return "\n".join(
        line for line in body.split("\n") if not _is_version_link_line(line, lang)
    )


def markdown_to_html(body, md_rel_path, lang):
    out = []
    lines = body.split("\n")
    i = 0
    n = len(lines)
    in_list = None

    def close_list():
        nonlocal in_list
        if in_list:
            out.append(f"</{in_list}>")
            in_list = None

    while i < n:
        line = lines[i]
        stripped = line.strip()

        # fenced code
        if stripped.startswith("```"):
            close_list()
            i += 1
            buf = []
            while i < n and not lines[i].strip().startswith("```"):
                buf.append(lines[i])
                i += 1
            i += 1
            out.append("<pre><code>" + escape("\n".join(buf)) + "</code></pre>")
            continue

        if not stripped:
            close_list()
            i += 1
            continue

        # horizontal rule
        if re.match(r"^([-*_])\1{2,}$", stripped):
            close_list()
            out.append("<hr />")
            i += 1
            continue

        # heading
        m = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if m:
            close_list()
            depth = len(m.group(1))
            # The page <h1> comes from frontmatter, so a leading "# Title" in
            # the body would duplicate it. Emit it as <h2> here and let
            # build_lang strip that first one; deeper levels map straight
            # across (## -> h2, ### -> h3) so section styling applies.
            level = max(depth, 2)
            out.append(f"<h{level}>{inline(m.group(2).strip())}</h{level}>")
            i += 1
            continue

        # blockquote
        if stripped.startswith(">"):
            close_list()
            buf = []
            while i < n and lines[i].strip().startswith(">"):
                buf.append(lines[i].strip().lstrip(">").strip())
                i += 1
            out.append(f"<blockquote><p>{inline(' '.join(buf))}</p></blockquote>")
            continue

        # table
        if "|" in stripped and i + 1 < n and re.match(r"^\|?[\s:|-]+\|[\s:|-]+$", lines[i + 1].strip()):
            close_list()
            header = [c.strip() for c in stripped.strip("|").split("|")]
            i += 2
            rows = []
            while i < n and "|" in lines[i] and lines[i].strip():
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            out.append('<table class="md-table">')
            out.append("<thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in header) + "</tr></thead><tbody>")
            for row in rows:
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in row) + "</tr>")
            out.append("</tbody></table>")
            continue

        # lists
        m_ul = re.match(r"^[-*+]\s+(.*)$", stripped)
        m_ol = re.match(r"^\d+[.)]\s+(.*)$", stripped)
        if m_ul or m_ol:
            want = "ul" if m_ul else "ol"
            if in_list != want:
                close_list()
                out.append(f"<{want}>")
                in_list = want
            out.append(f"<li>{inline((m_ul or m_ol).group(1))}</li>")
            i += 1
            continue

        # paragraph
        close_list()
        buf = [stripped]
        i += 1
        while i < n and lines[i].strip() and not re.match(
            r"^(#{1,6}\s|[-*+]\s|\d+[.)]\s|>|```|[-*_]{3,}$)", lines[i].strip()
        ):
            buf.append(lines[i].strip())
            i += 1
        out.append(f"<p>{inline(' '.join(buf))}</p>")

    close_list()
    return "\n".join(out)


