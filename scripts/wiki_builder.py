def parse_frontmatter(text):
    """Return (meta_dict, body). Handles the simple scalar/list YAML used here."""
    meta = {}
    if not text.startswith("---"):
        return meta, text
    end = text.find("\n---", 3)
    if end == -1:
        return meta, text
    block = text[3:end]
    rest = text[end + 4 :]
    rest = rest.lstrip("\n")

    for line in block.split("\n"):
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, _, val = line.partition(":")
        key = key.strip()
        val = val.strip()
        if val.startswith("[") and val.endswith("]"):
            items = [v.strip().strip("'\"") for v in val[1:-1].split(",")]
            meta[key] = [v for v in items if v]
        else:
            meta[key] = val.strip("'\"")

    # Some files repeat a bare `key: value` line right after the closing ---.
    # Drop leading body lines that are still frontmatter-shaped.
    lines = rest.split("\n")
    while lines and re.match(r"^[A-Za-z_][\w-]*:\s*(\S.*)?$", lines[0]) and not lines[0].startswith("#"):
        lines.pop(0)
    return meta, "\n".join(lines).lstrip("\n")


