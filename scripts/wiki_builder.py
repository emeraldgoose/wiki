def depth_to_root(rel_path):
    return "../" * (len(rel_path.split("/")) - 1)


def render_page(title, meta, body_html, lang, rel_path, toc_html="",
                other_href=None, other_has_page=True):
    s = STRINGS[lang]
    root = depth_to_root(rel_path)
    other = "ko" if lang == "en" else "en"
    # The header switch points at the same document in the other language so
    # readers stay in context. Without a counterpart it falls back to the
    # other portal (visually dimmed, title says so) instead of 404-ing.
    if other_href is None:
        other_href = f"/{other}/index.html"
        other_has_page = False
    switch_class = "lang-switch" + ("" if other_has_page else " is-fallback")
    switch_title = s["switch"] if other_has_page else s["switch_missing"]
    other_label = other.upper()

    meta_bits = []
    if meta.get("authors"):
        authors = meta["authors"]
        authors = ", ".join(authors) if isinstance(authors, list) else str(authors)
        meta_bits.append(
            f'<p class="doc-meta"><span class="label">{s["authors"]}</span> {escape(authors)}</p>'
        )
    pub = meta.get("published") or meta.get("published_date")
    if pub and str(pub).lower() not in ("true", "false"):
        meta_bits.append(
            f'<p class="doc-meta"><span class="label">{s["published"]}</span> {escape(str(pub))}</p>'
        )
    if meta.get("arxiv_id"):
        arxiv = escape(str(meta["arxiv_id"]))
        link = meta.get("url") or f"https://arxiv.org/abs/{arxiv}"
        meta_bits.append(
            f'<p class="doc-meta"><span class="label">{s["arxiv"]}</span> '
            f'<a href="{html.escape(str(link), quote=True)}" target="_blank" rel="noopener">{arxiv}</a></p>'
        )
    meta_html = "\n".join(meta_bits)

    toc_block = f'<nav class="toc"><p class="toc-title">{s["toc"]}</p>{toc_html}</nav>' if toc_html else ""

    return f"""<!DOCTYPE html>
<html lang="{s['lang']}" dir="ltr">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta name="description" content="{escape(title)}" />
<title>{escape(title)} — {s['portal']}</title>
<link rel="stylesheet" href="{root}assets/style.css" />
</head>
<body class="doc">
<header class="site-header">
  <div class="wrap header-inner">
    <a class="brand" href="{root}index.html">{s['portal_short']}</a>
    <nav class="header-nav">
      <a href="{root}index.html#recent">{s['nav_recent']}</a>
      <a href="{root}index.html#categories">{s['nav_categories']}</a>
      <a href="{root}index.html#sources">{s['nav_sources']}</a>
    </nav>
    <a class="{switch_class}" href="{other_href}" hreflang="{other}" title="{escape(switch_title)}">{other_label}</a>
  </div>
</header>

<div class="wrap">
  <article class="doc-body">
    <header class="doc-header">
      <h1>{escape(title)}</h1>
      <p class="subtitle">{s['subtitle']}</p>
      {meta_html}
    </header>
    {toc_block}
    <div class="prose">
{body_html}
    </div>
    <p class="back-link"><a href="{root}index.html">{s['back']}</a></p>
  </article>
</div>

<footer class="site-footer">
  <div class="wrap">
    <p>{s['footer']}</p>
  </div>
</footer>
</body>
</html>
"""


