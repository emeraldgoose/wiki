def collect_toc(body_html):
    """Small TOC built from the h2 headings already rendered."""
    items = re.findall(r'<h2 id="[^"]*">(.*?)</h2>', body_html)
    if not items:
        return ""
    parts = ["<ul>"]
    for inner in items:
        label = re.sub(r"<[^>]+>", "", inner)
        parts.append(f'<li><a href="#sec-{slug(label)}">{label}</a></li>')
    parts.append("</ul>")
    return "\n".join(parts)


def slug(text):
    """URL-safe anchor id.

    Must preserve non-ASCII: Korean and other CJK headings previously
    collapsed to an empty string, so every such heading got id="sec-" and the
    table of contents linked nowhere. Percent-encoding belongs to the URL
    layer, not to the id itself.
    """
    text = str(text).lower()
    # Keep word characters (including Hangul/CJK) and spaces; treat the rest
    # as separators.
    text = re.sub(r"[^\w\s-]", " ", text, flags=re.UNICODE)
    text = re.sub(r"[\s_]+", "-", text.strip())
    return re.sub(r"-{2,}", "-", text).strip("-") or "section"


def add_anchors(body_html):
    """Give each h2/h3 a stable, unique id so the TOC can link to it."""
    seen = {}

    def sub(match):
        level, inner = match.group(1), match.group(2)
        label = re.sub(r"<[^>]+>", "", inner)
        base_slug = slug(label)
        # Repeated headings ("Background" twice, "References" in both
        # languages) would otherwise collapse onto one id.
        count = seen.get(base_slug, 0)
        seen[base_slug] = count + 1
        anchor = base_slug if count == 0 else f"{base_slug}-{count + 1}"
        return f'<h{level} id="sec-{anchor}">{inner}</h{level}>'

    return re.sub(r"<h([23])>(.*?)</h\1>", sub, body_html)


def build_css():
    """Write static/<lang>/assets/style.css and deploy portal.js.

    Both live in scripts/ as the single source of truth (site_css.py and
    portal.js); edit them there rather than in the generated output.
    A missing portal.js is a build error, not a silent skip: without it
    every filter, sort and pagination control on the portal is dead.
    """
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from site_css import SHARED, DOC

    css = SHARED.rstrip() + "\n\n" + DOC.lstrip() + "\n"

    portal_src = os.path.join(os.path.dirname(os.path.abspath(__file__)), "portal.js")
    if not os.path.exists(portal_src):
        raise SystemExit(f"missing {portal_src} — portal interactivity would ship broken")
    with open(portal_src, "rb") as fh:
        portal_bytes = fh.read()
    for lang, pub in PUBLIC.items():
        target_dir = os.path.join(pub, "assets")
        os.makedirs(target_dir, exist_ok=True)
        with open(os.path.join(target_dir, "portal.js"), "wb") as out:
            out.write(portal_bytes)
        print(f"  deployed assets/portal.js into static/{lang}/")

    written = []
    for lang, pub in PUBLIC.items():
        target_dir = os.path.join(pub, "assets")
        os.makedirs(target_dir, exist_ok=True)
        css_path = os.path.join(target_dir, "style.css")
        with open(css_path, "w", encoding="utf-8") as f:
            f.write(css)
        written.append(css_path)
    return written


def build_lang(lang):
    src_root = os.path.join(CONTENT_DIR, lang)
    out_root = PUBLIC[lang]
    if not os.path.isdir(src_root):
        print(f"!! no content/{lang} directory, skipping", file=sys.stderr)
        return 0

    written = 0
    for dirpath, _dirnames, filenames in os.walk(src_root):
        for name in sorted(filenames):
            if not name.endswith(".md") or name in SKIP_NAMES:
                continue
            src = os.path.join(dirpath, name)
            rel = os.path.relpath(src, src_root).replace(os.sep, "/")
            with open(src, "r", encoding="utf-8", errors="replace") as f:
                raw = f.read()

            meta, body = parse_frontmatter(raw)
            body = rewrite_md_links(body, rel, lang)
            body = strip_version_links(body, lang)
            body_html = markdown_to_html(body, rel, lang)
            body_html = add_anchors(body_html)
            # The body's leading "# <title>" duplicates the <h1> in the header.
            body_html = re.sub(
                r'^<h2 id="[^"]*">.*?</h2>\s*', "", body_html, count=1, flags=re.S
            )

            title = meta.get("title") or re.sub(r"[_-]+", " ", name[:-3]).strip()
            if not title:
                m = re.search(r"^#\s+(.*)$", body, re.M)
                title = m.group(1).strip() if m else name[:-3]

            out_rel = rel[:-3] + ".html"
            out_path = os.path.join(out_root, out_rel)
            os.makedirs(os.path.dirname(out_path), exist_ok=True)
            toc = collect_toc(body_html)
            # Header language switch: same document in the other language when
            # its source exists, otherwise the other portal as fallback.
            other = "ko" if lang == "en" else "en"
            if os.path.isfile(os.path.join(CONTENT_DIR, other, rel)):
                other_href = f"/{other}/{out_rel}"
                other_has_page = True
            else:
                other_href = f"/{other}/index.html"
                other_has_page = False
            with open(out_path, "w", encoding="utf-8") as f:
                f.write(render_page(title, meta, body_html, lang, out_rel, toc,
                                    other_href, other_has_page))
            written += 1

    print(f"  {lang}: wrote {written} pages")
    return written


def prune_orphans(lang):
    """Delete generated .html files with no corresponding source .md.

    Renaming or removing a source file otherwise leaves a stale page behind:
    it stays in the output tree and gets linked from nothing, which is how
    duplicate/renamed article directories accumulated orphans.
    """
    src_root = os.path.join(CONTENT_DIR, lang)
    out_root = PUBLIC[lang]
    expected = set()
    for dirpath, _dirs, files in os.walk(src_root):
        for name in files:
            if not name.endswith(".md") or name in SKIP_NAMES:
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), src_root)
            expected.add(rel[:-3] + ".html")

    removed = 0
    for dirpath, _dirs, files in os.walk(out_root):
        for name in files:
            if not name.endswith(".html"):
                continue
            full = os.path.join(dirpath, name)
            rel = os.path.relpath(full, out_root)
            if rel in expected:
                continue
            if name in HAND_WRITTEN_OUTPUTS:
                continue
            os.remove(full)
            removed += 1
    return removed


def main():
    print("Build: content -> static/en / static/ko")
    css_paths = build_css()
    for path in css_paths:
        print(f"  wrote {os.path.relpath(path, CWD)}")
    total = sum(build_lang(lang) for lang in LANGS)
    for lang, pub in PUBLIC.items():
        for name in STALE_OUTPUTS:
            stale = os.path.join(pub, name)
            if os.path.exists(stale):
                os.remove(stale)
                print(f"  removed stale {os.path.relpath(stale, CWD)}")
        removed = prune_orphans(lang)
        if removed:
            print(f"  pruned {removed} orphaned page(s) from static/{lang}/")
    print(f"Build completed: {total} pages across {len(LANGS)} languages")
    if total == 0:
        raise SystemExit("no pages written — content directories are empty")

    # Guard: a source file that produced no page is a silent failure. This
    # previously shipped a builder with no entry point, which wrote nothing
    # and still exited 0, so the cron reported success on a no-op.
    # A stub is a placeholder for an unwritten article. Rendering it is fine,
    # but the build must never be the thing that quietly lets one ship: the
    # original RSS failure was 40 empty files published as if they were real.
    pending = []
    for lang in LANGS:
        src_root = os.path.join(CONTENT_DIR, lang)
        for dirpath, _dirs, files in os.walk(src_root):
            for fname in files:
                if not fname.endswith(".md"):
                    continue
                full = os.path.join(dirpath, fname)
                try:
                    with open(full, encoding="utf-8", errors="replace") as fh:
                        head = fh.read(3000)
                except OSError:
                    continue
                if "status: pending" in head or "[Content pending]" in head:
                    pending.append(os.path.relpath(full, CWD))
    if pending:
        print(
            f"  NOTE: {len(pending)} article(s) are still stubs "
            f"([Content pending]) and render as placeholders",
            file=sys.stderr,
        )
        for path in sorted(pending)[:5]:
            print(f"        {path}", file=sys.stderr)
        if len(pending) > 5:
            print(f"        ... and {len(pending) - 5} more", file=sys.stderr)

    for lang in LANGS:
        src_root = os.path.join(CONTENT_DIR, lang)
        sources = [
            name
            for _dp, _dn, fnames in os.walk(src_root)
            for name in fnames
            if name.endswith(".md") and name not in SKIP_NAMES
        ]
        built = sum(
            1
            for _dp, _dn, fnames in os.walk(PUBLIC[lang])
            for _f in fnames
            if _f.endswith(".html") and _f not in HAND_WRITTEN_OUTPUTS
        )
        if built < len(sources):
            print(
                f"  WARNING: {len(sources)} source .md but {built} .html under "
                f"static/{lang}/ ({len(sources) - built} unbuilt)",
                file=sys.stderr,
            )
            if built == 0:
                raise SystemExit(f"static/{lang} has no generated pages — build did not run")
    print("Build verified: page counts match source counts")


if __name__ == "__main__":
    main()